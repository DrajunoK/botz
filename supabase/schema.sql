-- ───────────── friends ─────────────
create table public.friendships (
  user_id uuid not null references auth.users (id) on delete cascade,
  friend_id uuid not null references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, friend_id),
  check (user_id <> friend_id)
);

alter table public.friendships enable row level security;
create policy "read own friendships" on public.friendships
  for select to authenticated using (user_id = auth.uid());
create policy "delete own friendships" on public.friendships
  for delete to authenticated using (user_id = auth.uid());
grant select, delete on public.friendships to authenticated;

-- Adding a friend by code is mutual and goes through this function only.
create function public.add_friend(code text) returns text
language plpgsql security definer set search_path = '' as $$
declare
  target uuid;
  nick text;
begin
  if auth.uid() is null then raise exception 'not signed in'; end if;
  select id, nickname into target, nick
    from public.profiles where friend_code = upper(trim(code));
  if target is null then raise exception 'unknown friend code'; end if;
  if target = auth.uid() then raise exception 'cannot add yourself'; end if;
  insert into public.friendships (user_id, friend_id)
    values (auth.uid(), target), (target, auth.uid())
    on conflict do nothing;
  return nick;
end $$;

-- ───────────── stats ─────────────
-- local_2p (two people on one phone) is stored but never counted against friends or globally.

create view public.my_stats with (security_invoker = true) as
select game, context, mode,
       count(*) filter (where result = 'win') as wins,
       count(*) filter (where result = 'loss') as losses,
       count(*) filter (where result = 'draw') as draws
from public.matches
where user_id = auth.uid()
group by game, context, mode;

create view public.my_tournament_stats with (security_invoker = true) as
select mode,
       count(*) filter (where result = 'win') as wins,
       count(*) filter (where result = 'loss') as losses,
       count(*) filter (where result = 'draw') as draws
from public.tournaments
where user_id = auth.uid()
group by mode;

grant select on public.my_stats, public.my_tournament_stats to authenticated;

-- Wins/losses of each friend, per game (game is null for a friend with no match yet).
create function public.friends_stats()
returns table (friend_id uuid, nickname text, game text, wins bigint, losses bigint)
language sql security definer stable set search_path = '' as $$
  select f.friend_id, p.nickname, m.game,
         count(*) filter (where m.result = 'win'),
         count(*) filter (where m.result = 'loss')
  from public.friendships f
  join public.profiles p on p.id = f.friend_id
  left join public.matches m on m.user_id = f.friend_id and m.mode <> 'local_2p'
  where f.user_id = auth.uid()
  group by f.friend_id, p.nickname, m.game
$$;

create function public.friends_tournament_stats()
returns table (friend_id uuid, nickname text, wins bigint, losses bigint)
language sql security definer stable set search_path = '' as $$
  select f.friend_id, p.nickname,
         count(*) filter (where t.result = 'win'),
         count(*) filter (where t.result = 'loss')
  from public.friendships f
  join public.profiles p on p.id = f.friend_id
  left join public.tournaments t on t.user_id = f.friend_id and t.mode <> 'local_2p'
  where f.user_id = auth.uid()
  group by f.friend_id, p.nickname
$$;

-- Global rankings across all users. p_game null = every game.
create function public.leaderboard(p_game text default null, p_limit int default 50)
returns table (nickname text, wins bigint, losses bigint)
language sql security definer stable set search_path = '' as $$
  select p.nickname,
         count(*) filter (where m.result = 'win'),
         count(*) filter (where m.result = 'loss')
  from public.matches m
  join public.profiles p on p.id = m.user_id
  where m.mode <> 'local_2p' and (p_game is null or m.game = p_game)
  group by p.id, p.nickname
  order by 2 desc, 3 asc
  limit least(p_limit, 100)
$$;

create function public.tournament_leaderboard(p_limit int default 50)
returns table (nickname text, wins bigint, losses bigint)
language sql security definer stable set search_path = '' as $$
  select p.nickname,
         count(*) filter (where t.result = 'win'),
         count(*) filter (where t.result = 'loss')
  from public.tournaments t
  join public.profiles p on p.id = t.user_id
  where t.mode <> 'local_2p'
  group by p.id, p.nickname
  order by 2 desc, 3 asc
  limit least(p_limit, 100)
$$;

