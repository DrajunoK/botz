-- Botz stats schema (includes 002 and 003 for a fresh project). Paste once into Supabase -> SQL Editor -> Run.
-- Requires: Authentication -> Sign In / Providers -> "Allow anonymous sign-ins" ON.
-- "Automatically expose new tables" is OFF, so every grant below is explicit.

-- ───────────── profiles ─────────────
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nickname text not null default 'Joueur' check (char_length(nickname) between 2 and 20),
  friend_code text not null unique,
  created_at timestamptz not null default now()
);

create function public.make_friend_code() returns text
language plpgsql as $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; -- no 0/O/1/I
  code text;
begin
  loop
    code := '';
    for i in 1..6 loop
      code := code || substr(alphabet, 1 + floor(random() * length(alphabet))::int, 1);
    end loop;
    exit when not exists (select 1 from public.profiles where friend_code = code);
  end loop;
  return code;
end $$;

-- Every new (anonymous) user gets a profile with a random nickname and friend code.
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  nick text;
begin
  loop
    nick := 'Joueur' || floor(1000 + random() * 9000)::int;
    exit when not exists (select 1 from public.profiles where lower(nickname) = lower(nick));
  end loop;
  insert into public.profiles (id, nickname, friend_code)
  values (new.id, nick, public.make_friend_code());
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create unique index profiles_nickname_unique on public.profiles (lower(nickname));

alter table public.profiles enable row level security;
create policy "read own profile" on public.profiles
  for select to authenticated using (id = auth.uid());
create policy "update own profile" on public.profiles
  for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
grant select on public.profiles to authenticated;
grant update (nickname) on public.profiles to authenticated;

-- ───────────── matches (one row per mini-game played) ─────────────
-- id is generated by the phone so an offline retry can never create a duplicate.
-- `verified` and `opponent_id` can only be written by the future authoritative server.
create table public.matches (
  id uuid primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  game text not null check (game in ('soccer', 'survivor', 'petanque')),
  mode text not null check (mode in ('vs_ai', 'local_2p', 'online')),
  context text not null check (context in ('single', 'tournament')),
  tournament_id uuid,
  result text not null check (result in ('win', 'loss', 'draw')),
  score_for smallint,
  score_against smallint,
  opponent_id uuid references auth.users (id) on delete set null,
  verified boolean not null default false,
  played_at timestamptz not null default now() check (played_at <= now() + interval '1 day')
);
create index matches_user_game on public.matches (user_id, game);
create index matches_game on public.matches (game);

alter table public.matches enable row level security;
create policy "read own matches" on public.matches
  for select to authenticated using (user_id = auth.uid());
create policy "insert own matches" on public.matches
  for insert to authenticated with check (user_id = auth.uid());
grant select on public.matches to authenticated;
grant insert (id, game, mode, context, tournament_id, result, score_for, score_against, played_at)
  on public.matches to authenticated;

